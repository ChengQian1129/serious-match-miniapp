const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const YAML = require('yaml')

const root = path.resolve(__dirname, '..')
const auditRoot = path.join(root, 'design', 'public-language-audit')
const outputPath = path.join(root, 'shared', 'content', 'public-language.generated.js')
const claimCopyPath = path.join(root, 'shared', 'content', 'claim-copy.js')

function readYaml(name) {
  return YAML.parse(fs.readFileSync(path.join(auditRoot, name), 'utf8'))
}

function digest(name) {
  return crypto.createHash('sha256').update(fs.readFileSync(path.join(auditRoot, name))).digest('hex')
}

function parseCsv(text) {
  const rows = []
  let row = []
  let field = ''
  let quoted = false
  for (let index = 0; index < text.length; index += 1) {
    const character = text[index]
    if (quoted) {
      if (character === '"' && text[index + 1] === '"') {
        field += '"'
        index += 1
      } else if (character === '"') {
        quoted = false
      } else {
        field += character
      }
    } else if (character === '"') {
      quoted = true
    } else if (character === ',') {
      row.push(field)
      field = ''
    } else if (character === '\n') {
      row.push(field)
      rows.push(row)
      row = []
      field = ''
    } else if (character !== '\r') {
      field += character
    }
  }
  if (field || row.length) {
    row.push(field)
    rows.push(row)
  }
  return rows
}

function csvObjects(name) {
  const rows = parseCsv(fs.readFileSync(path.join(auditRoot, name), 'utf8'))
  const headers = rows.shift().map(header => header.replace(/^\uFEFF/, ''))
  return rows.filter(row => row.some(Boolean)).map(row => Object.fromEntries(headers.map((header, index) => [header, row[index] || ''])))
}

function addOption(target, key, code, text) {
  if (!target[key]) target[key] = {}
  target[key][String(code)] = text
}

function buildV3Copy() {
  const rows = csvObjects('V3_ALL_USER_FACING_STRINGS_AUDIT.csv')
  const copy = {
    taskPrompts: {},
    childPrompts: {},
    taskOptions: {},
    responseFormatOptions: {},
    taskSpecificOptions: {}
  }
  rows.forEach(row => {
    const id = row.surface_id
    const replacement = row.recommended_text
    if (!replacement || !['REWRITE', 'ADD'].includes(row.decision)) return
    if (row.kind === 'parent_prompt') copy.taskPrompts[id] = replacement
    if (row.kind === 'child_prompt') copy.childPrompts[id] = replacement
    if (row.kind === 'task_specific_response_option') {
      const match = id.match(/^(.+):LEVEL5_OVERRIDE:(\d+)$/)
      if (match) addOption(copy.taskSpecificOptions, match[1], match[2], replacement)
    }
    if (row.kind === 'response_option') {
      const formatMatch = id.match(/^responseFormat:([^:]+):(\d+)$/)
      if (formatMatch) addOption(copy.responseFormatOptions, formatMatch[1], formatMatch[2], replacement)
      const taskMatch = id.match(/^(.+):option:(\d+)$/)
      if (taskMatch) addOption(copy.taskOptions, taskMatch[1], taskMatch[2], replacement)
    }
  })
  return copy
}

function render(value) {
  return `// Generated by scripts/sync-public-language.js. Do not hand-edit.\nmodule.exports = ${JSON.stringify(value, null, 2)}\n`
}

function renderClaimCopy(value) {
  return `// Generated by scripts/sync-public-language.js. Do not hand-edit.\nconst CLAIM_COPY = Object.freeze(${JSON.stringify(value, null, 2)})\n\nfunction resolveClaimCopy(definition) {\n  const key = typeof definition === 'string' ? definition : definition && (definition.copyKey || definition.id)\n  return CLAIM_COPY[key] || {}\n}\n\nmodule.exports = { CLAIM_COPY, resolveClaimCopy }\n`
}

function publicValue(value) {
  if (Array.isArray(value)) return value.map(publicValue).filter(item => item !== undefined)
  if (!value || typeof value !== 'object') return value
  if (Object.prototype.hasOwnProperty.call(value, 'replaceWith')) return value.replaceWith
  if (value.action === 'DELETE') return undefined
  return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, publicValue(child)]).filter(([, child]) => child !== undefined))
}

function pickPublic(source, keys) {
  return Object.fromEntries(keys.map(key => [key, publicValue(source && source[key])]).filter(([, value]) => value !== undefined))
}

function projectChapters(source) {
  return Object.fromEntries(['C1', 'C2', 'C3', 'C4', 'C5', 'C6'].map(chapterId => [chapterId, pickPublic(source && source[chapterId], ['eyebrow', 'title', 'body', 'hint'])]))
}

function projectChapterInsight(source) {
  return pickPublic(source, ['headerPattern', 'evidenceToggle', 'evidenceIntro', 'supporting', 'contradicting', 'qualifying', 'answerPrefix', 'fallback'])
}

function projectResult(source) {
  return pickPublic(source, [
    'pageTitle', 'heroIntro', 'topFindingsTitle', 'chapterResultsTitle', 'detailsTitle', 'detailsAction',
    'detailsCollapseAction', 'unknownTitle', 'unknownDescription', 'observationTitle', 'boundary',
    'reviseTitle', 'dataTitle', 'dataDelete', 'deleteDialogTitle', 'deleteDialogContent', 'mapAction',
    'followupTitle', 'followupBody', 'followupAction', 'claimAction'
  ])
}

function projectRelationshipMap(source) {
  return pickPublic(source, [
    'title', 'preferredFutureSections', 'claimsTitle', 'claimsDescription', 'unknownTitle',
    'unknownDescription', 'historyTitle', 'historyDescription', 'followupTitle', 'followupDescription',
    'followupAction', 'reportAction', 'claimBasis'
  ])
}

function projectFollowup(source) {
  return pickPublic(source, ['entry', 'intro', 'settings', 'scopes'])
}

function projectPrivacy(source) {
  return pickPublic(source, ['operator', 'contact', 'retentionTitle', 'retention', 'rightsTitle', 'rights'])
}

function projectV2Copy(source) {
  const chapterNarrativePublic = Object.fromEntries(Object.entries(source.chapterNarrativePublic || {}).filter(([chapterId]) => /^C[1-6]$/.test(chapterId)).map(([chapterId, states]) => [
    chapterId,
    Object.fromEntries(Object.entries(states).map(([stateId, value]) => [stateId, Array.isArray(value) ? { headline: value[0], summary: value[1] } : { headline: value.headline, summary: value.summary }]))
  ]))
  return {
    scaleOverrides: source.scaleOverrides,
    chapterTitles: source.chapterTitles,
    itemTextOverrides: source.itemTextOverrides,
    claimCopyOverrides: source.claimCopyOverrides,
    chapterInsightFallback: pickPublic(source.chapterInsightFallback, ['title', 'text']),
    reportFallback: pickPublic(source.reportFallback, ['title', 'subtitle', 'unknownTitle', 'unknownText', 'answerUnavailable', 'shareTitle']),
    claimDefaults: pickPublic(source.claimDefaults, ['alternativeExplanations', 'verificationQuestions']),
    fallbackClaims: publicValue(source.fallbackClaims),
    chapterNarrativePublic
  }
}

function projectNarratives(source) {
  function projectNarrativeState(value) {
    if (Array.isArray(value)) return { headline: value[0] || '', summary: value[1] || '' }
    if (typeof value === 'string') return { headline: value, summary: '' }
    if (value && typeof value === 'object') return { headline: value.headline || '', summary: value.summary || '' }
    return { headline: '', summary: '' }
  }
  const dimensions = Object.fromEntries(Object.entries(source.dimensions || {}).map(([dimensionId, states]) => [
    dimensionId,
    Object.fromEntries(Object.entries(states).map(([stateId, value]) => [stateId, projectNarrativeState(value)]))
  ]))
  const chapters = Object.fromEntries(Object.entries(source.chapters || {}).map(([chapterId, value]) => {
    const projected = { label: value.label }
    Object.entries(value).filter(([key]) => key !== 'label').forEach(([stateId, state]) => {
      projected[stateId] = projectNarrativeState(state)
    })
    return [chapterId, projected]
  }))
  const crossChapterPatterns = Object.fromEntries(Object.entries(source.crossChapterPatterns || {}).map(([patternId, value]) => [patternId, { headline: value.headline, summary: value.summary }]))
  const chapterCompositions = publicValue(source.chapterCompositions || {})
  return { dimensions, chapters, crossChapterPatterns, chapterCompositions, reportTitles: source.reportTitles || {} }
}

function main() {
  const ui = readYaml('PUBLIC_UI_COPY_REWRITE.yaml')
  const v2 = readYaml('V2_PUBLIC_COPY_REWRITE.yaml')
  const v3Narrative = readYaml('V3_PUBLIC_NARRATIVE_OVERRIDE.yaml')
  const v3Product = readYaml('V3_PRODUCT_PREVIEW_COPY.yaml')
  const forbidden = readYaml('PUBLIC_FORBIDDEN_LANGUAGE.yaml')
  const publicUi = {
    navigation: pickPublic(ui.navigation, ['globalFallback', 'welcome', 'home', 'questionnaire', 'chapterInsight', 'result', 'relationshipMapRouteVisibleTitle', 'claimEvidence', 'followupIntro', 'followupSettings', 'profile', 'privacy', 'v3Pilot']),
    welcome: pickPublic(ui.welcome, ['title', 'intro', 'questions', 'boundary', 'meta', 'action', 'methodAction']),
    home: pickPublic(ui.home, ['titleFirstTime', 'titleResume', 'description', 'exampleLabel', 'example', 'action', 'guideAction', 'progressTitle', 'completedTitle', 'completedDescription', 'topicsTitle', 'topics', 'followupHint']),
    methodGuide: pickPublic(ui.methodGuide, ['title', 'body', 'focus', 'detailAction', 'closeAction']),
    chapters: projectChapters(ui.chapters),
    chapterInsight: projectChapterInsight(ui.chapterInsight),
    result: projectResult(ui.result),
    relationshipMap: projectRelationshipMap(ui.relationshipMap),
    followup: projectFollowup(ui.followup),
    privacy: projectPrivacy(ui.privacy),
    v3Pilot: {
      pageTitle: ui.v3Pilot.pageTitle,
      skipDisplay: ui.v3Pilot.skipDisplay,
      completion: ui.v3Pilot.completion,
      completionNote: ui.v3Pilot.completionNote,
      completionFollowup: ui.v3Pilot.completionFollowup
    },
    v3P0Research: publicValue(ui.v3P0Research || {})
  }
  const value = {
    schemaVersion: 'serious-match.public-language.registry.v1.0',
    generatedAt: ui.generatedAt,
    sourceDigests: Object.fromEntries([
      'PUBLIC_UI_COPY_REWRITE.yaml',
      'V2_PUBLIC_COPY_REWRITE.yaml',
      'V3_ALL_USER_FACING_STRINGS_AUDIT.csv',
      'V3_PUBLIC_NARRATIVE_OVERRIDE.yaml',
      'V3_PRODUCT_PREVIEW_COPY.yaml',
      'PUBLIC_FORBIDDEN_LANGUAGE.yaml'
    ].map(name => [name, digest(name)])),
    ui: publicUi,
    v2: projectV2Copy(v2),
    v3: Object.assign(buildV3Copy(), {
      narratives: projectNarratives(v3Narrative),
      product: publicValue(v3Product.product || {}),
      productV0: publicValue(v3Product.productV0 || {})
    }),
    publicErrors: Object.fromEntries(['saveFailed', 'loadFailed', 'submitFailed', 'questionInvalid', 'incomplete', 'network', 'generic'].map(key => [key, ui.errors[key]]))
  }
  fs.mkdirSync(path.dirname(outputPath), { recursive: true })
  fs.writeFileSync(outputPath, render(value), 'utf8')
  fs.writeFileSync(claimCopyPath, renderClaimCopy(v2.claimCopyOverrides || {}), 'utf8')
  console.log(`Public language registry synced: ${outputPath}`)
}

if (require.main === module) main()

module.exports = { parseCsv, csvObjects, buildV3Copy, outputPath }
