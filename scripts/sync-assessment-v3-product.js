const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const YAML = require('yaml')

const root = path.resolve(__dirname, '..')
const normativeRoot = path.join(root, 'research', 'v3', 'normative')
const authoringPath = path.join(normativeRoot, 'user_report_authoring_library.yaml')
const combinePath = path.join(normativeRoot, 'dimension_combine_conclusion.yaml')
const outputPath = path.join(root, 'shared', 'assessment-v3-product', 'normative-generated.js')

function readYaml(filePath) {
  return YAML.parse(fs.readFileSync(filePath, 'utf8'))
}

function digest(filePath) {
  return crypto.createHash('sha256').update(fs.readFileSync(filePath)).digest('hex')
}

function parseValue(value) {
  const token = String(value).trim()
  if (token === 'TRUE') return true
  if (token === 'FALSE') return false
  if (token.startsWith('[') && token.endsWith(']')) {
    return token.slice(1, -1).split(',').map(item => item.trim()).filter(Boolean)
  }
  return token
}

function compileTrigger(rawTrigger) {
  const match = String(rawTrigger).trim().match(/^([A-Za-z0-9_.]+)\s*(>=|<=|=|in)\s*(.+)$/)
  if (!match) throw new Error(`Unsupported V3 cross-chapter trigger: ${rawTrigger}`)
  const operator = match[2]
  const value = parseValue(match[3])
  if (operator === 'in' && !Array.isArray(value)) throw new Error(`The in trigger must use a list: ${rawTrigger}`)
  if (operator !== 'in' && Array.isArray(value)) throw new Error(`Only in triggers may use a list: ${rawTrigger}`)
  return { field: match[1], operator, value }
}

function buildBundle() {
  const authoring = readYaml(authoringPath)
  const combine = readYaml(combinePath)
  const patterns = (authoring.crossChapterPatterns || []).map((pattern, order) => ({
    patternId: pattern.patternId,
    triggers: (pattern.triggers || []).map(compileTrigger),
    priority: pattern.priority || 'LOW',
    maxUsePerReport: pattern.maxUsePerReport || 1,
    order
  }))
  const c3 = combine.chapters && combine.chapters.C3
  if (!c3 || !Array.isArray(c3.dimensions) || !c3.rule) throw new Error('Normative C3 chapter rule is missing')
  return {
    schemaVersion: 'serious-match.v3-product-normative.v1.0',
    generatedAt: authoring.generatedAt || combine.generatedAt || new Date().toISOString().slice(0, 10),
    sourceDigests: {
      'user_report_authoring_library.yaml': digest(authoringPath),
      'dimension_combine_conclusion.yaml': digest(combinePath)
    },
    crossChapterPatterns: patterns,
    c3ChapterRule: {
      dimensions: c3.dimensions,
      rule: c3.rule,
      examples: c3.examples || {}
    }
  }
}

function render(value) {
  return `// Generated by scripts/sync-assessment-v3-product.js. Do not hand-edit.\nmodule.exports = ${JSON.stringify(value, null, 2)}\n`
}

function main() {
  const bundle = buildBundle()
  fs.mkdirSync(path.dirname(outputPath), { recursive: true })
  fs.writeFileSync(outputPath, render(bundle), 'utf8')
  console.log(`V3 product normative bundle synced: ${outputPath}`)
}

if (require.main === module) main()

module.exports = { compileTrigger, buildBundle, render, outputPath }
