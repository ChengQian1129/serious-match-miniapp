const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const YAML = require('yaml')
const sync = require('./sync-assessment-v3-product-v0')
const runtime = require('../shared/assessment-v3-product-v0/runtime-engine')
const { DIMENSION_IDS, CHAPTERS } = require('../shared/assessment-v3-product/contract')

const root = path.resolve(__dirname, '..')
const read = file => YAML.parse(fs.readFileSync(path.join(root, file), 'utf8'))
const questionnaire = read('research/v3/product-v0/product_questionnaire_v0.yaml')
const audit = read('research/v3/product-v0/product_item_selection_audit.yaml')
const coverage = read('research/v3/product-v0/product_coverage_audit.yaml')
const scoring = read('research/v3/product-v0/provisional_scoring_v0.yaml')
const decisionMap = read('research/v3/product-v0/decision_map_v0.yaml')
const reportCore = read('research/v3/normative/report_core_candidate.yaml')
const app = require('../app.json')
const { FEATURES } = require('../utils/features')

assert.equal(questionnaire.status, 'THEORY_DRIVEN_PROVISIONAL')
assert.equal(questionnaire.counts.parentTasks, reportCore.parentTaskCount)
assert.equal(questionnaire.orderedParentTaskIds.length, reportCore.parentTaskCount)
assert.equal(questionnaire.counts.responseFields, questionnaire.responseFieldIds.length)
assert.equal(new Set(questionnaire.responseFieldIds).size, questionnaire.responseFieldIds.length)
assert.equal(audit.decisions.length, reportCore.parentTaskCount)
assert.equal(new Set(audit.decisions.map(row => row.taskId)).size, reportCore.parentTaskCount)
assert.deepEqual(new Set(audit.decisions.map(row => row.taskId)), new Set(reportCore.orderedParentTaskIds))
assert.equal(audit.decisions.every(row => row.decision === 'KEEP_PRODUCT_V0'), true)
questionnaire.orderedParentTaskIds.forEach(id => {
  assert.ok(reportCore.tasks[id], `Product v0 task ${id} missing from REPORT_CORE`)
  assert.ok(questionnaire.tasks[id].sourceTaskId === id)
})
DIMENSION_IDS.forEach(dimensionId => {
  const chapter = CHAPTERS.find(item => item.dimensionIds.includes(dimensionId))
  assert.ok(coverage.dimensions[dimensionId] && coverage.dimensions[dimensionId].covered, `${dimensionId} lacks coverage`)
  assert.equal(questionnaire.chapters[chapter.id].dimensionTaskIds[dimensionId].length > 0, true)
})
assert.equal(Object.keys(coverage.strategyCoverage).length, 8)
assert.equal(Object.values(coverage.strategyCoverage).every(value => value.covered), true)
assert.equal(coverage.parts.l3.covered && coverage.parts.l4.covered && coverage.parts.l5.covered, true)
assert.equal(decisionMap.independentFromDimensions, true)
assert.equal(scoring.status, 'THEORY_DRIVEN_PROVISIONAL')
assert.equal(scoring.empiricallyCalibrated, false)
assert.equal(scoring.directionCoverage.everyOrderedItemExplicit, true)
assert.equal(Object.keys(scoring.itemDirections).length, questionnaire.counts.responseFields)
Object.entries(scoring.itemDirections).forEach(([itemId, direction]) => assert.ok(['POSITIVE', 'REVERSE', 'DIRECT', 'NOT_APPLICABLE'].includes(direction), `${itemId} has unknown direction`))
assert.equal(fs.readFileSync(path.join(root, 'shared/assessment-v3-product-v0/runtime-engine.js'), 'utf8').includes('node:fs'), false)
assert.ok(app.pages.includes('pages/questionnaire-v3/index'))
assert.equal(FEATURES.v3ProductV0, false)
assert.equal(runtime.BUNDLE.orderedParentTaskIds.length, questionnaire.counts.parentTasks)
assert.equal(runtime.BUNDLE.responseFieldIds.length, questionnaire.counts.responseFields)

console.log(`assessment-v3-product-v0 static checks OK: ${questionnaire.counts.parentTasks} parent tasks, ${questionnaire.counts.responseFields} response fields, 14 dimensions, 8 strategy families`)
