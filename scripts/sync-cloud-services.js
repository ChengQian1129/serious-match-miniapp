function wrapper(name, actions) {
  return `const core = require('./core')\n\nconst ACTIONS = new Set(${JSON.stringify(actions, null, 2)})\n\nexports.main = async event => {\n  if (!event || !ACTIONS.has(event.action)) return { ok: false, code: 'UNKNOWN_ACTION', message: '不支持的操作' }\n  return core.main(event)\n}\n`
}

function generatedProductFiles() {
  const productBundle = require(path.join(root, 'shared/assessment-v3-product-v0/questionnaire-bundle.js'))
  const productScoring = require(path.join(root, 'shared/assessment-v3-product-v0/scoring-bundle.js'))
  const normative = require(path.join(root, 'shared/assessment-v3-product/normative-generated.js'))
  const generated = value => `// Generated by scripts/sync-cloud-services.js. Do not hand-edit.\nmodule.exports = ${JSON.stringify(value)}\n`
  const replace = (file, replacements) => replacements.reduce((source, [from, to]) => source.replaceAll(from, to), fs.readFileSync(path.join(root, file), 'utf8'))

  return new Map([
    ['assessment-v3-product-v0-questionnaire.generated.js', generated(productBundle)],
    ['assessment-v3-product-v0-scoring.generated.js', generated(productScoring)],
    ['assessment-v3-product-normative.generated.js', generated(normative)],
    ['assessment-v3-product-contract.generated.js', replace('shared/assessment-v3-product/contract.js', [["require('./normative-generated')", "require('./assessment-v3-product-normative.generated')"]])],
    ['assessment-v3-product-pattern-eligibility.generated.js', replace('shared/assessment-v3-product/pattern-eligibility.js', [
      ["require('./normative-generated')", "require('./assessment-v3-product-normative.generated')"],
      ["require('./contract')", "require('./assessment-v3-product-contract.generated')"]
    ])],
    ['assessment-v3-product-v0-runtime.generated.js', replace('shared/assessment-v3-product-v0/runtime-engine.js', [
      ["require('./questionnaire-bundle')", "require('./assessment-v3-product-v0-questionnaire.generated')"],
      ["require('./scoring-bundle')", "require('./assessment-v3-product-v0-scoring.generated')"],
      ["require('../assessment-v3-product/contract')", "require('./assessment-v3-product-contract.generated')"]
    ])],
    ['assessment-v3-product-report-renderer.generated.js', replace('shared/assessment-v3-product/report-renderer.js', [
      ["require('../content/public-language.generated')", "require('./public-language.generated')"],
      ["require('../assessment-v3-pilot/runtime-engine')", "require('./assessment-v3-product-v0-runtime.generated')"],
      ["require('./contract')", "require('./assessment-v3-product-contract.generated')"],
      ["require('./pattern-eligibility')", "require('./assessment-v3-product-pattern-eligibility.generated')"]
    ])],
    ['public-language.generated.js', fs.readFileSync(path.join(root, 'shared/content/public-language.generated.js'), 'utf8')]
  ])
}

function expectedFiles(name, actions) {
  const files = new Map([
    ['index.js', wrapper(name, actions)],
    ['core.js', fs.readFileSync(path.join(sourceDir, 'index.js'), 'utf8')],
    ['package.json', fs.readFileSync(path.join(sourceDir, 'package.json'), 'utf8')]
  ])
  fs.readdirSync(sourceDir).filter(file => /^assessment-v2-.*\.js$/.test(file)).forEach(file => files.set(file, fs.readFileSync(path.join(sourceDir, file), 'utf8')))
  generatedProductFiles().forEach((content, file) => files.set(file, content))
  return files
}

function sync() {
  generatedProductFiles().forEach((content, file) => fs.writeFileSync(path.join(sourceDir, file), content))
  Object.entries(services).forEach(([name, actions]) => {
    const targetDir = path.join(root, 'cloudfunctions', name)
    fs.mkdirSync(targetDir, { recursive: true })
    expectedFiles(name, actions).forEach((content, file) => fs.writeFileSync(path.join(targetDir, file), content))
  })
  console.log('Cloud service packages synced:', Object.keys(services).join(', '))
}

if (require.main === module) sync()
module.exports = { services, expectedFiles, sync }
